"""
LangChain में Messages वो structured तरीके हैं जिनसे हम LLM को बातचीत का इतिहास और भूमिका (role) बताते हैं।

जब हम Chat Model (जैसे ChatGPT, Claude, Grok आदि) को इस्तेमाल करते हैं, तो साधारण string की जगह Message 
objects भेजते हैं। इससे मॉडल को साफ पता चलता है कि कौन बोल रहा है।

!Messages are objects that contain:
    * Role      - Identifies the message type (e.g. system, user)
    * Content   - Represents the actual content of the message (like text, images, audio, documents, etc.)
    * Metadata  - Optional fields such as response information, message IDs, and token usage
    
    
? System message    - Tells the model how to behave and provide context for interactions
? Human message     - Represents user input and interactions with the model
? AI message        - Responses generated by the model, including text content, tool calls, and metadata
"""


from dotenv import load_dotenv
from langchain_groq import ChatGroq
from langchain.messages import SystemMessage, AIMessage, HumanMessage

load_dotenv()

llm = ChatGroq( 
    model="openai/gpt-oss-120b"
)

messages = [
    SystemMessage(content="you're helful assistant"),
    HumanMessage(
        content=f"What is the weather in Lucknow?", # content hain
        additional_kwargs={"location": "Lucknow"} # metadeta hain
    ),
]

response = llm.invoke(messages)
print(response.content)